#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen_netlists_r3.py — 方案 A 第 3 轮复测网表生成器（规格 v4 口径）

与 `gen_netlists_r5.py` 的区别（第 3 轮 ask 的五条新要求）
-----------------------------------------------------------
1. **主评分口径 = 真实 OPA388 模型**。所有维度都另出一套 `V9*` 网表（TI 模型在
   `lib/OPAx388.LIB`）；`V1–V8`（0 Ω 理想源）保留为**对照报告**，不参与打分。
2. **D6 拆分**：
   * D6a 需要「同带宽跟随器自身噪声」基线 → 新增 `V9dn`：阶梯电阻与 130 kΩ 差分
     负载全部改成 `R_NOISELESS`（T_ABS=−273.15，热噪声归零），只留 TI 模型的内部噪声源。
   * D6b = 完整网表的积分噪声（V9d）。
3. **D8 按 R·C 乘积异向配对**：`V9p_{m}_{pair|same}`，m ∈ {0.1 %, 0.5 %, 1 %}
   * pair：线 B = R×(1+m)、C_gnd 与 C_diff ×(1−m)
   * same：线 B = R×(1+m)、C×(1+m)（同向失配，对照）
4. **C9 peaking**：由 `V9a` 的全频段（1 Hz–2 MHz）增益曲线直接取峰值，另跑
   `V9pk`（同拓扑、只存引脚节点、dec 2000，定位峰值频率与 -6 dB 判据）。
5. **D5 必须实测**：`V9c`（0 Ω 源）/`V9f`（600 kΩ 样品端）用 trap 积分器、
   最大步长 2 ns、窗口 500 µs（ask 允许的三条补救全部用上）。

命名：全部文件带 `_r3` 后缀，落在 `r5_work/r3/`。

用法::

    python gen_netlists_r3.py            # 生成全部网表（不跑）
    python gen_netlists_r3.py --list     # 只列文件名
"""
from __future__ import annotations

import argparse
import json
import os

import gen_netlists_r5 as G

HERE = os.path.dirname(os.path.abspath(__file__))
OUTDIR = os.path.join(HERE, "r5_work", "r3")
LIB = G.LIB_OPA388

FMOD, MCLK = 4.096e6, 16.384e6
TOPT = ".options plotwinsize=0 reltol=1e-6 abstol=1e-12 vntol=1e-9 chgtol=1e-15 trtol=1"
# 瞬态：trap + 2 ns 最大步长（ask 的补救组合之一）
TT = ".options plotwinsize=0 method=trap reltol=1e-5 abstol=1e-11 vntol=1e-8 " \
     "chgtol=1e-14 trtol=2"


def _head(tag: str, note: str) -> list:
    return [f"* r3 {tag} - {note}",
            "* generated by gen_netlists_r3.py (spec v4: real OPA388 primary)"]


def _line(side: str, src: str, node: str, stages, noiseless=False) -> list:
    """支路：src — R1 — n1(C1) — R2 — n2(C2) — …

    ``noiseless=True`` 时电阻改用 `R_NOISELESS` 模型（T_ABS=−273.15 K → 无热噪声），
    用于给 D6a 建立「同带宽跟随器自身噪声」基线。
    """
    out, prev = [], src
    for i, (r, cg, _cd) in enumerate(stages, 1):
        if noiseless:
            out.append(f"R{side}{i} {prev} {node}{i} R_NOISELESS {r:.10g}")
        else:
            out.append(f"R{side}{i} {prev} {node}{i} {r:.10g}")
        out.append(f"C{side}{i} {node}{i} 0 {cg:.10g}")
        prev = f"{node}{i}"
    return out


def _common(stages, noiseless_load=False) -> list:
    a, b = f"pa{len(stages)}", f"na{len(stages)}"
    cd = stages[-1][2]
    out = [f"Cd {a} {b} {cd:.10g}"]
    if noiseless_load:
        out.append(f"Rin {a} {b} R_NOISELESS 130000")
    else:
        out.append(f"Rin {a} {b} 130000")
    out += [f"Cpa {a} 0 5e-12", f"Cna {b} 0 5e-12"]
    return out


def _pwr() -> list:
    return [f".include {LIB}", f"Vcc vcc 0 DC {G.VCC}", "Vee vee 0 DC 0"]


def _foll(vp="vp", vn="vn") -> list:
    return [f"Xfa {vp} fpa vcc vee fpa OPAx388",
            f"Xfb {vn} fna vcc vee fna OPAx388"]


# ---------------------------------------------------------------- 真实模型 AC
def v9a_ac(cand, stages=None, tag="v9a", note="AC DM, TI OPA388 (D1/D3/D4/D10/C9)"):
    st = stages or cand["stages"]
    a, b = f"pa{len(st)}", f"na{len(st)}"
    L = _head(tag, note) + _pwr()
    L += ["Vp vp 0 DC 2 AC 0.5", "Vn vn 0 DC 2 AC -0.5"] + _foll()
    L += _line("a", "fpa", "pa", st) + _line("b", "fna", "na", st) + _common(st)
    L += [".ac dec 600 0.1 200Meg", TOPT,
          f".meas AC g_dc   FIND mag(V({a})-V({b})) AT 0.1",
          f".meas AC g_16k  FIND mag(V({a})-V({b})) AT 16k",
          f".meas AC g_fmod FIND mag(V({a})-V({b})) AT 4.096Meg",
          f".meas AC g_mclk FIND mag(V({a})-V({b})) AT 16.384Meg",
          ".end"]
    return "\n".join(L) + "\n"


def v9b_cm(cand, stages=None, tag="v9b", note="AC CM, TI OPA388 (D2)"):
    st = stages or cand["stages"]
    a = f"pa{len(st)}"
    L = _head(tag, note) + _pwr()
    L += ["Vp vp 0 DC 2 AC 1", "Vn vn 0 DC 2 AC 1"] + _foll()
    L += _line("a", "fpa", "pa", st) + _line("b", "fna", "na", st) + _common(st)
    L += [".ac dec 600 0.1 200Meg", TOPT,
          f".meas AC g_dc   FIND mag(V({a})) AT 0.1",
          f".meas AC g_fmod FIND mag(V({a})) AT 4.096Meg",
          f".meas AC g_mclk FIND mag(V({a})) AT 16.384Meg",
          ".end"]
    return "\n".join(L) + "\n"


def v9pk_ac(cand, stages=None, tag="v9pk", note="full-band peaking probe (C9)"):
    """C9：真实模型全频段增益峰值。1 Hz–20 MHz、2000 点/dec，只存两引脚节点。"""
    st = stages or cand["stages"]
    a, b = f"pa{len(st)}", f"na{len(st)}"
    L = _head(tag, note) + _pwr()
    L += ["Vp vp 0 DC 2 AC 0.5", "Vn vn 0 DC 2 AC -0.5"] + _foll()
    L += _line("a", "fpa", "pa", st) + _line("b", "fna", "na", st) + _common(st)
    L += [f".save V({a}) V({b})", ".ac dec 2000 1 20Meg", TOPT, ".end"]
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- 真实模型噪声
def v9d_noise(cand, stages=None, tag="v9d", noiseless=False):
    """D6b（noiseless=False）/ D6a 基线（noiseless=True）。"""
    st = stages or cand["stages"]
    a, b = f"pa{len(st)}", f"na{len(st)}"
    note = ("noise, TI OPA388, ladder+load %s (D6%s)"
            % ("noiseless" if noiseless else "noisy", "a baseline" if noiseless else "b"))
    L = _head(tag, note) + _pwr()
    if noiseless:
        L += [".model R_NOISELESS RES (T_ABS=-273.15)"]
    L += ["Vp vp 0 DC 2 AC 1", "Vn vn 0 DC 2 AC 0"] + _foll()
    L += _line("a", "fpa", "pa", st, noiseless) + _line("b", "fna", "na", st, noiseless)
    L += _common(st, noiseless_load=noiseless)
    L += [f".noise V({a},{b}) Vp dec 200 0.1 2.048Meg", TOPT, ".end"]
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- 真实模型瞬态
def v9e_ac600k(cand, stages=None, tag="v9e",
               note="AC DM at 600k sample end, TI OPA388 (V9 high-Z addendum)"):
    """规格 §5.1 高源阻抗工况的 AC 版：600 kΩ 样品端 + 真实跟随器。"""
    st = stages or cand["stages"]
    a, b = f"pa{len(st)}", f"na{len(st)}"
    L = _head(tag, note) + _pwr()
    L += ["Vp vp 0 DC 2 AC 0.5", "Vn vn 0 DC 2 AC -0.5",
          "Rsa vp fa 600k", "Rsb vn fb 600k"] + _foll("fa", "fb")
    L += _line("a", "fpa", "pa", st) + _line("b", "fna", "na", st) + _common(st)
    L += [".ac dec 600 0.1 200Meg", TOPT,
          f".meas AC g_dc   FIND mag(V({a})-V({b})) AT 0.1",
          f".meas AC g_16k  FIND mag(V({a})-V({b})) AT 16k",
          f".meas AC g_fmod FIND mag(V({a})-V({b})) AT 4.096Meg",
          f".meas AC g_mclk FIND mag(V({a})-V({b})) AT 16.384Meg",
          ".end"]
    return "\n".join(L) + "\n"


def v9c_tran(cand, stages=None, tag="v9c", high_z=False,
             note=None, tstop="500u", tstep="2n"):
    """D5 实测：0 Ω 源（high_z=False）或 600 kΩ 样品端（high_z=True）。"""
    st = stages or cand["stages"]
    note = note or ("settling, R x1.01 C x1.05, %s, TI OPA388 (D5)"
                    % ("600k sample end" if high_z else "0 ohm source"))
    L = _head(tag, note) + _pwr()
    L += ["Vp vp 0 PULSE(2 3 10u 10n 10n 600u 2m)",
          "Vn vn 0 PULSE(2 1 10u 10n 10n 600u 2m)"]
    if high_z:
        L += ["Rsa vp fa 600k", "Rsb vn fb 600k"] + _foll("fa", "fb")
    else:
        L += _foll()
    L += _line("a", "fpa", "pa", st) + _line("b", "fna", "na", st) + _common(st)
    L += [f".save V(pa{len(st)}) V(na{len(st)}) V(fpa) V(fna)"]
    L += [f".tran 0 {tstop} 0 {tstep}", TT, ".end"]
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- 真实模型 kickback
def v9k_kick(cand, ron=1.0, stages=None, tag=None, tstop="1.2u", tstep="2n",
             edge="10n"):
    st = stages or cand["stages"]
    n = len(st)
    a, b = f"pa{n}", f"na{n}"
    tag = tag or f"v9k_ron{ron:g}"
    L = _head(tag, f"kickback with TI OPA388, Ron={ron:g} (D9)")
    L += [".model SWK SW(Ron=%g Roff=1e12 Vt=0.5 Vh=0)" % ron] + _pwr()
    L += ["Vp vp 0 DC 3.2", "Vn vn 0 DC 0.8", "Vcm vcm 0 DC 2.0"] + _foll()
    L += _line("a", "fpa", "pa", st) + _line("b", "fna", "na", st) + _common(st)
    L += [f"S1a {a} csa swp 0 SWK", f"Csa csa vcm {G.ADC_CS_PF/2*1e-12:.10g}",
          "S2a csa vcm swn 0 SWK",
          f"S1b {b} csb swn 0 SWK", f"Csb csb vcm {G.ADC_CS_PF/2*1e-12:.10g}",
          "S2b csb vcm swp 0 SWK",
          "Vswp swp 0 PULSE(0 1 0 %s %s 121.07n 244.1406n)" % (edge, edge),
          "Vswn swn 0 PULSE(0 1 122.07n %s %s 121.07n 244.1406n)" % (edge, edge),
          f".save V({a}) V({b}) V(csa) V(csb) V(fpa) V(fna)",
          f".tran 0 {tstop} 0 {tstep}",
          ".options plotwinsize=0 reltol=1e-5 abstol=1e-12 vntol=1e-8 "
          "chgtol=1e-15 trtol=2", ".end"]
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- D8 配对失配
def v9p_cmrr(cand, m, paired=True, stages=None, tag=None):
    """D8：两线失配的 CM→DM 变换（真实模型）。

    线 A 标称；线 B：
      paired=True  → R×(1+m)，C_gnd 与 C_diff ×(1−m)   （R·C 乘积 ≈ 不变）
      paired=False → R×(1+m)，C ×(1+m)                 （同向失配，对照）
    """
    st = stages or cand["stages"]
    n = len(st)
    a, b = f"pa{n}", f"na{n}"
    km = 1.0 - m if paired else 1.0 + m
    st_b = [(r * (1.0 + m), c * km, cd * km) for r, c, cd in st]
    kind = "pair" if paired else "same"
    tag = tag or f"v9p_m{m:g}_{kind}"
    L = _head(tag, "CM->DM, TI OPA388, m=%.3g%% %s (D8)" % (m * 100, kind))
    L += _pwr()
    L += ["Vp vp 0 DC 2 AC 1", "Vn vn 0 DC 2 AC 1"] + _foll()
    L += _line("a", "fpa", "pa", st) + _line("b", "fna", "na", st_b) + _common(st)
    L += [".ac dec 200 10 40k", TOPT,
          f".meas AC dm_10  FIND mag(V({a})-V({b})) AT 10",
          f".meas AC dm_1k  FIND mag(V({a})-V({b})) AT 1k",
          f".meas AC dm_16k FIND mag(V({a})-V({b})) AT 16k",
          f".meas AC cm_10  FIND mag((V({a})+V({b}))/2) AT 10",
          ".end"]
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- 真实模型 MC AC
def v9m_mc(cand, k, smp, tag=None):
    """D7：真实模型 30 次蒙特卡洛（R ±1 %、C ±5 %，逐元件独立）。"""
    st = cand["stages"]
    tag = tag or f"v9m_mc{k:02d}"
    n = len(st)
    a, b = f"pa{n}", f"na{n}"
    st_a = G._apply(st, smp["ra"], smp["ca"], smp["cd"])
    st_b = G._apply(st, smp["rb"], smp["cb"], smp["cd"])
    L = _head(tag, "MC AC #%02d with TI OPA388 (D7)" % k) + _pwr()
    L += ["Vp vp 0 DC 2 AC 0.5", "Vn vn 0 DC 2 AC -0.5"] + _foll()
    L += _line("a", "fpa", "pa", st_a) + _line("b", "fna", "na", st_b) + _common(st_a)
    L += ["Vp vp 0 DC 2 AC 0.5", "Vn vn 0 DC 2 AC -0.5"]
    L += [f".save V({a}) V({b})", ".ac dec 200 0.1 100k", TOPT, ".end"]
    # 去掉重复的激励行（上面重复了一次）
    seen = set()
    L2 = []
    for ln in L:
        if ln.startswith("Vp vp") or ln.startswith("Vn vn"):
            if ln in seen:
                continue
            seen.add(ln)
        L2.append(ln)
    return "\n".join(L2) + "\n"


# ---------------------------------------------------------------- 汇总
def generate(key: str, cand: dict, outdir: str = OUTDIR) -> list:
    G.RS = 0.0                                # 规格 §5.1：V1–V8 理想源 0 Ω
    os.makedirs(outdir, exist_ok=True)
    files = []

    def w(name, text):
        with open(os.path.join(outdir, f"r5_{key}_r3_{name}.net"), "w",
                  encoding="ascii", newline="\n") as fh:
            fh.write(text)
        files.append(f"r5_{key}_r3_{name}.net")

    st = [tuple(map(float, s)) for s in cand["stages"]]
    ns = len(st)

    # ---- 0 Ω 理想源对照（V1–V8，规格 §7 原清单）----
    w("v1", G.gen_v1(cand))
    w("v2", G.gen_v2(cand))
    w("v3", G.gen_v3(cand))
    w("v4", G.gen_v4(cand))
    w("v4b", G.gen_v4b(cand))
    w("v7", G.gen_v7(cand))
    for ron in (1.0, 100.0, 1000.0):
        w(f"v8_ron{ron:g}", G.gen_v8(cand, ron))
    for tt in (-20.0, 85.0):
        w(f"v1t{int(tt):+d}C", G.gen_v1_temp(cand, tt))
    for k, smp in enumerate(G.mc_samples(n=G.N_MC, n_stage=ns), 1):
        w(f"v5mc{k:02d}", G.gen_v5(cand, k, smp))
        w(f"v6mc{k:02d}", G.gen_v6(cand, k, smp))

    # ---- 真实模型（主评分口径）----
    w("v9a", v9a_ac(cand))
    w("v9b", v9b_cm(cand))
    w("v9pk", v9pk_ac(cand))
    w("v9d", v9d_noise(cand, noiseless=False))
    w("v9dn", v9d_noise(cand, st, tag="v9dn", noiseless=True))
    corner = [(r * 1.01, c * 1.05, cd * 1.05) for r, c, cd in st]
    w("v9e", v9e_ac600k(cand))
    w("v9c", v9c_tran(cand, stages=corner, tag="v9c"))
    w("v9f", v9c_tran(cand, stages=corner, tag="v9f", high_z=True))
    w("v9k_ron1", v9k_kick(cand, 1.0))
    for m in (0.001, 0.005, 0.01):
        w(f"v9p_m{m:g}_pair", v9p_cmrr(cand, m, paired=True))
        w(f"v9p_m{m:g}_same", v9p_cmrr(cand, m, paired=False))
    for k, smp in enumerate(G.mc_samples(n=G.N_MC, n_stage=ns), 1):
        w(f"v9m_mc{k:02d}", v9m_mc(cand, k, smp))
    return files


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cand", default="A")
    ap.add_argument("--outdir", default=OUTDIR)
    ap.add_argument("--list", action="store_true")
    args = ap.parse_args(argv)
    with open(os.path.join(HERE, "r5_candidates_r2.json"), encoding="utf-8") as fh:
        cand = json.load(fh)[args.cand]
    files = generate(args.cand, cand, args.outdir)
    print(f"方案 {args.cand}: {len(files)} 个网表 → {args.outdir}")
    if args.list:
        for f in files:
            print("   ", f)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
