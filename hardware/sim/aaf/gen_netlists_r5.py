    L = _header(tag, note)
    L += _v9_head()
    # 单 3.3 V 轨：信号必须坐在 2.0 V 共模上（0 V 与负压超出 OPA388 输出摆幅）
    L += ["Vp vp 0 PULSE(2 3 10u 10n 10n 600u 2m)",
          "Vn vn 0 PULSE(2 1 10u 10n 10n 600u 2m)",
          "Xfa vp fpa vcc vee fpa OPAx388", "Xfb vn fna vcc vee fna OPAx388"]
    L += _line("a", "fpa", "pa", _scaled(st, 1.01, 1.05))
    L += _line("b", "fna", "na", _scaled(st, 1.01, 1.05))
    L += _common(_scaled(st, 1.01, 1.05))
    L += _save(len(st), "V(fpa) V(fna)")
    # TI 模型的内部 1F 电容会咬住步长：放宽 reltol 且只存必要向量
    L += [".tran 0 300u 0 20n",
          ".options plotwinsize=0 method=gear reltol=1e-5 abstol=1e-11 vntol=1e-8 chgtol=1e-14 trtol=7",
          ".end"]
    return "\n".join(L) + "\n"


