# ---------------------------------------------------------------- 常量（规格口径）
FMOD = 4.096e6
MCLK = 16.384e6
# 源内阻：规格 sec 5.1 规定 V1–V6 用 **0 Ω 理想源**；opt_engine.ladder_matrices()
# 第 20 行把 rs 硬编码 1 Ω（数值稳定）。`--rs` 覆盖；默认 0 = 规格口径，
# 交叉验证时用 `--rs 1` 生成引擎镜像网表（两者 @fMOD 差 1.08 dB，不可混比）。
RS = 0.0
CPIN = 5e-12             # 引擎 CPIN 5 pF/线
RLOAD_DM = 130e3         # M3：ADS131A02 差分输入阻抗 130 kΩ（跨 AINP/AINN）
VCM_DC = 2.0             # sec 5.1 标准测试条件：直流偏置 2.0 V
ADC_CS_PF = 3.5          # M2 差分采样电容（每侧 Cs/2 = 1.75 pF）
ADC_RSW = 1.0            # M6：手册未给；规格 sec 7 缺省 Ron=1 Ω（明示为假设）
VCC = 3.3                # 3.3 V_A 模拟轨

N_MC = 30
TOL_R = 0.01             # sec 5.1 D7：R ±1%
TOL_C = 0.05             # 前战役口径：C0G ±5%
MC_SEED = 20261018

# 瞬态/AC 求解精度：判 0.01% 建立（2 V 阶跃 → 200 µV）时默认 reltol=1e-3 远不够
TOPT = ".options plotwinsize=0 reltol=1e-6 abstol=1e-12 vntol=1e-9 chgtol=1e-15 trtol=1"


# ---------------------------------------------------------------- 网表构件
def _fmt(x: float) -> str:
    """数值 → 网表串（保留足够有效位，避免取整损失）。"""
    return f"{x:.10g}"


def _line(side: str, src: str, node: str, stages) -> list:
    """一条支路：src — Rs — node0 — R1 — node1(C1) — … — nodeN(CN)。

    Rs == 0 时**不画电阻**（真 0 Ω 理想源，规格 sec 5.1 口径）；画成 `0` 会让
    LTspice 插入 1 mΩ 级的内部处理，破坏与解析极限（rs→0）的严格对拍。
    """
    out = []
    if RS > 0:
        out.append(f"R{side}s {src} {node}0 {_fmt(RS)}")
        first = f"{node}0"
    else:
        first = src
    prev = first
    for i, (r, cg, _cd) in enumerate(stages, 1):
        out.append(f"R{side}{i} {prev} {node}{i} {_fmt(r)}")
        out.append(f"C{side}{i} {node}{i} 0 {_fmt(cg)}")
        prev = f"{node}{i}"
    return out


def _common(stages, a="pa", b="na", rload=RLOAD_DM) -> list:
    """公共件：末级跨接 C_diff、差分负载、引脚对地电容。"""
    out = []
    cd = stages[-1][2]
    if cd > 0:
        out.append(f"Cd {a}{len(stages)} {b}{len(stages)} {_fmt(cd)}")
    if rload > 0:
        out.append(f"Rin {a}{len(stages)} {b}{len(stages)} {_fmt(rload)}")
    out.append(f"Cpa {a}{len(stages)} 0 {_fmt(CPIN)}")
    out.append(f"Cna {b}{len(stages)} 0 {_fmt(CPIN)}")
    return out


def _scaled(stages, kr, kc):
    return [(r * kr, cg * kc, cd * kc) for r, cg, cd in stages]


def _header(tag: str, note: str) -> list:
    return [f"* r5 {tag} - {note}", "* generated by gen_netlists_r5.py (spec v4 sec 5.1/7)"]


# ---------------------------------------------------------------- V1 标称 AC 差分
def gen_v1(cand, stages=None, tag="V1", note="nominal AC differential (D1/D3/D4/D10)"):
    st = stages or cand["stages"]
    pa, na = f"pa{len(st)}", f"na{len(st)}"
    L = _header(tag, note)
    # sec 5.1：AC 1 V 差分（±0.5 V/线）、DC 2.0 V
    L += ["Vp vp 0 DC 2 AC 0.5", "Vn vn 0 DC 2 AC -0.5"]
    L += _line("a", "vp", "pa", st)
    L += _line("b", "vn", "na", st)
    L += _common(st)
    L += [".ac dec 400 0.1 200Meg", TOPT,
          f".meas AC g_dc   FIND mag(V({pa})-V({na})) AT 0.1",
          f".meas AC g_16k  FIND mag(V({pa})-V({na})) AT 16k",
          f".meas AC g_fmod FIND mag(V({pa})-V({na})) AT 4.096Meg",
          f".meas AC g_mclk FIND mag(V({pa})-V({na})) AT 16.384Meg",
          ".end"]
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- V2 标称 AC 共模
def gen_v2(cand, stages=None, tag="V2", note="nominal AC common mode (D2)"):
    st = stages or cand["stages"]
    pa, na = f"pa{len(st)}", f"na{len(st)}"
    L = _header(tag, note)
    L += ["Vp vp 0 DC 2 AC 1", "Vn vn 0 DC 2 AC 1"]      # sec 5.1：共模 1 V AC
    L += _line("a", "vp", "pa", st)
    L += _line("b", "vn", "na", st)
    L += _common(st)
    L += [".ac dec 400 0.1 200Meg", TOPT,
          f".meas AC g_dc   FIND mag(V({pa})) AT 0.1",
          f".meas AC g_fmod FIND mag(V({pa})) AT 4.096Meg",
          f".meas AC g_mclk FIND mag(V({pa})) AT 16.384Meg",
          f".meas AC g_d16k FIND mag(V({pa})-V({na})) AT 16k",
          ".end"]
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- V3 失配角 AC 共模
def gen_v3(cand, stages=None, tag="V3",
           note="mismatch AC common mode, line-B R,C x1.01 (D8)"):
    st = stages or cand["stages"]
    pa, na = f"pa{len(st)}", f"na{len(st)}"
    L = _header(tag, note)
    L += ["Vp vp 0 DC 2 AC 1", "Vn vn 0 DC 2 AC 1"]
    L += _line("a", "vp", "pa", st)                        # 标称线
    L += _line("b", "vn", "na", _scaled(st, 1.01, 1.01))   # 与引擎 tol_r=tol_c=1% 同构
    L += _common(st)
    L += [".ac dec 400 1 100k", TOPT,
          f".meas AC cm_10  FIND mag(V({pa}))       AT 10",
          f".meas AC cm_1k  FIND mag(V({pa}))       AT 1k",
          f".meas AC cm_16k FIND mag(V({pa}))       AT 16k",
          f".meas AC dm_10  FIND mag(V({pa})-V({na})) AT 10",
          f".meas AC dm_1k  FIND mag(V({pa})-V({na})) AT 1k",
          f".meas AC dm_16k FIND mag(V({pa})-V({na})) AT 16k",
          ".end"]
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- V4 瞬态建立
def _save(nstage, extra="") -> list:
    """只存判定需要的向量，否则 OPA388 模型的内部节点会把 .raw 撑到 GB 级。"""
    return [f".save V(pa{nstage}) V(na{nstage}) V(vp) V(vn) {extra}".replace("  ", " ")]


def _tran_core(stages, tstop="500u", tstep="10n", amp=1.0) -> list:
    """差分阶跃 2 V（±amp 每线），0.01% 带 = 120 µV 差分（引擎 60 µV 单边）。"""
    L = [f"Vp vp 0 PULSE(0 {amp} 10u 10n 10n 600u 2m)",
         f"Vn vn 0 PULSE(0 -{amp} 10u 10n 10n 600u 2m)"]
    L += _line("a", "vp", "pa", stages)
    L += _line("b", "vn", "na", stages)
    L += _common(stages)
    L += _save(len(stages))
    L += [f".tran 0 {tstop} 0 {tstep}", TOPT, ".end"]
    return L


def gen_v4(cand, stages=None, tag="V4", note="worst-corner transient settling (D5)"):
    st = stages or cand["stages"]
    L = _header(tag, note)
    L += ["* corner: R x1.01, C x1.05 (engine tol_r=1%, tol_c=5%)"]
    L += _tran_core(_scaled(st, 1.01, 1.05))
    return "\n".join(L) + "\n"


def gen_v1_temp(cand, temp, tag=None, note=None):
    """规格 §5.1 温度角：只报通带相关项（D4/D7 趋势），不做全维度温度角。

    电容温漂按 C0G 的 −30 ppm/°C **显式折进容值**（LTspice 电容缺省 TC1=0，不折就恒等于 25 °C）。
    电阻温漂**未代入**：BOM 未定型（E.10 #6 归用户核实），报告须明示该假设。
    """
    st = cand["stages"]
    tag = tag or f"V1t{int(temp):+d}C"
    kc = 1.0 + (-30e-6) * (temp - 25.0)
    L = _header(tag, note or f"AC DM at {temp:+.0f} degC (C0G -30 ppm/degC folded into C)")
    L += ["* resistor tempco NOT applied: BOM not frozen (E.10 #6 owned by user)"]
    L += ["Vp vp 0 DC 2 AC 0.5", "Vn vn 0 DC 2 AC -0.5"]
    stx = _scaled(st, 1.0, kc)
    L += _line("a", "vp", "pa", stx)
    L += _line("b", "vn", "na", stx)
    L += _common(stx)
    pa, na = f"pa{len(st)}", f"na{len(st)}"
    L += [f".temp {temp:g}", ".ac dec 400 0.1 200Meg", TOPT,
          f".meas AC g_dc   FIND mag(V({pa})-V({na})) AT 0.1",
          f".meas AC g_16k  FIND mag(V({pa})-V({na})) AT 16k",
          f".meas AC g_fmod FIND mag(V({pa})-V({na})) AT 4.096Meg",
          ".end"]
    return "\n".join(L) + "\n"


def gen_v4b(cand, stages=None, tag="V4b",
            note="settle @600k source side, unbootstrapped Cin (D5 worst-case addendum)"):
    """sec 5.1 高源阻抗工况：600 kΩ 样品端 → 跟随器输入电容 → 理想跟随器 → 阶梯。

    注：理想源阶段（V1–V6）源阻抗规定 0 Ω，故 600 kΩ 只能加在**跟随器输入侧**；
    这里取未自举输入电容作**悲观上界**（OPAx388.LIB：C_C_COM0/1 = 4.5 pF 各端、
    C_C_DIFF = 2 pF 差分 → DM 等效 4.5 + 2×2 = 8.5 pF/线）。真实跟随器自举后远小于此，
    V9 用 TI 原模型给出真实值。该 RC 的 τ = 600k × 8.5p = 5.1 µs。
    """
    st = stages or cand["stages"]
    stx = _scaled(st, 1.01, 1.05)
    L = _header(tag, note)
    L += ["Vsa sa 0 PULSE(0 1 10u 10n 10n 600u 2m)",
          "Vsb sb 0 PULSE(0 -1 10u 10n 10n 600u 2m)",
          "Rsa_src sa fa 600k", "Rsb_src sb fb 600k",
          "Cfa fa 0 8.5p", "Cfb fb 0 8.5p",
          "Efa fa_o 0 fa 0 1", "Efb fb_o 0 fb 0 1"]   # 理想跟随器（输入电容已在上面）
    L += _line("a", "fa_o", "pa", stx)
    L += _line("b", "fb_o", "na", stx)
    L += _common(stx)
    L += _save(len(stx), "V(fa) V(fb) V(fa_o) V(fb_o)")
    L += [".tran 0 500u 0 10n", TOPT, ".end"]
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- V5/V6 蒙特卡洛
def mc_samples(n=N_MC, seed=MC_SEED, n_stage=4):
    """确定性 MC：每个元件（两线各自、C_diff 单个）独立乘子。

    返回 list of dict：
      {"ra": [...], "ca": [...], "rb": [...], "cb": [...], "cd": 乘子}
    """
    rng = np.random.default_rng(seed)
    out = []
    for _ in range(n):
        out.append({
            "ra": list(rng.uniform(1 - TOL_R, 1 + TOL_R, n_stage)),
            "ca": list(rng.uniform(1 - TOL_C, 1 + TOL_C, n_stage)),
            "rb": list(rng.uniform(1 - TOL_R, 1 + TOL_R, n_stage)),
            "cb": list(rng.uniform(1 - TOL_C, 1 + TOL_C, n_stage)),
            "cd": float(rng.uniform(1 - TOL_C, 1 + TOL_C)),
        })
    return out


def _apply(stages, kr_list, kc_list, kcd=1.0):
    out = []
    for i, (r, cg, cd) in enumerate(stages):
        out.append((r * kr_list[i], cg * kc_list[i], cd * (kcd if i == len(stages) - 1 else 1.0)))
    return out


def _two_lines(st_a, st_b, a="pa", b="na"):
    L = _line("a", "vp", a, st_a)
    L += _line("b", "vn", b, st_b)
    return L


def gen_v5(cand, k, smp, tag=None, note="MC AC #%02d (D7)"):
    st = cand["stages"]
    tag = tag or f"V5mc{k:02d}"
    st_a = _apply(st, smp["ra"], smp["ca"], smp["cd"])
    L = _header(tag, note % k)
    L += ["Vp vp 0 DC 2 AC 0.5", "Vn vn 0 DC 2 AC -0.5"]
    L += _line("a", "vp", "pa", st_a)
    L += _line("b", "vn", "na", _apply(st, smp["rb"], smp["cb"], smp["cd"]))
    L += _common(st_a)          # C_diff 也要吃 MC 扰动（原用未扰动的 st，D7 会低估离散度）
    L += [".ac dec 200 0.1 100k", TOPT, ".end"]
    return "\n".join(L) + "\n"


def gen_v6(cand, k, smp, tag=None, note="MC transient #%02d (D5 statistics)"):
    st = cand["stages"]
    tag = tag or f"V6mc{k:02d}"
    st_a = _apply(st, smp["ra"], smp["ca"], smp["cd"])
    L = _header(tag, note % k)
    L += [f"Vp vp 0 PULSE(0 1 10u 10n 10n 600u 2m)",
          f"Vn vn 0 PULSE(0 -1 10u 10n 10n 600u 2m)"]
    L += _line("a", "vp", "pa", st_a)
    L += _line("b", "vn", "na", _apply(st, smp["rb"], smp["cb"], smp["cd"]))
    L += _common(st_a)
    L += _save(len(st))
    L += [".tran 0 400u 0 10n", TOPT, ".end"]
    return "\n".join(L) + "\n"


