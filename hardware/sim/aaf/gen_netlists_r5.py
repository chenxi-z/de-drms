# ---------------------------------------------------------------- V8 Kickback
def gen_v8(cand, ron=ADC_RSW, stages=None, tag=None, note=None):
    """ADC 采样开关模型（sec 7 构建规范 + M2/M6）。

    每侧：pin —S1— Cs/2(1.75 pF) —S2— VCM(2.0 V)，S1/S2 **180° 反相、各 50%**（M6 p29 Fig.37/38）；
    两侧 S1 反相（差分两半反相工作）。周期 t_MOD = 1/fMOD = 244.1406 ns，导通 122.07 ns。
    Ron 手册未给（M6）→ 按规格 sec 7 缺省 1 Ω 建模，另跑 100 / 1000 Ω 灵敏度。
    """
    st = stages or cand["stages"]
    tag = tag or f"V8_ron{ron:g}"
    note = note or f"kickback, ADC sampling switch Ron={ron:g} ohm (D9)"
    L = _header(tag, note)
    L += ["* assumption: Ron not in datasheet (M6); spec 7 default 1 ohm; Cs=3.5 pF diff (M2)",
          f".model SWK SW(Ron={_fmt(ron)} Roff=1e12 Vt=0.5 Vh=0)"]
    # 最坏引脚电平：P 线 3.2 V、N 线 0.8 V，VCM = 2.0 V（相对 VCM ±1.2 V）
    L += ["Vp vp 0 DC 3.2", "Vn vn 0 DC 0.8", "Vcm vcm 0 DC 2.0"]
    L += _line("a", "vp", "pa", st)
    L += _line("b", "vn", "na", st)
    L += _common(st)
    # 开关必须接在**引脚节点** paN/naN 上（原写法接悬空节点 pa/na，引脚看不到 kickback）
    pin_a, pin_b = f"pa{len(st)}", f"na{len(st)}"
    L += [f"S1a {pin_a} csa swp 0 SWK", f"Csa csa vcm {_fmt(ADC_CS_PF/2*1e-12)}",
          "S2a csa vcm swn 0 SWK",
          f"S1b {pin_b} csb swn 0 SWK", f"Csb csb vcm {_fmt(ADC_CS_PF/2*1e-12)}",
          "S2b csb vcm swp 0 SWK",
          "Vswp swp 0 PULSE(0 1 0 0.5n 0.5n 121.07n 244.1406n)",
          "Vswn swn 0 PULSE(0 1 122.07n 0.5n 0.5n 121.07n 244.1406n)"]
    L += _save(len(st), "V(csa) V(csb)")
    # 40 µs 而非 4 µs：采样电流每个周期从阶梯抽电荷，网络要用 ~30 µs 才进入
    # 周期性稳态（实测 29.4 µs 处周期间差 <0.0004 µV）；4 µs 窗内测到的是启动暂态，
    # 不是 kickback 回稳能力（会把 D9 误判为不合格）。
    L += [".tran 0 40u 0 0.1n", TOPT, ".end"]
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- V9 真实 OPA388
def _v9_head():
    return [f".include {LIB_OPA388}", f"Vcc vcc 0 DC {VCC}", "Vee vee 0 DC 0"]


def gen_v9a(cand, stages=None, tag="V9a", note="AC DM with TI OPAx388 follower"):
    st = stages or cand["stages"]
    pa, na = f"pa{len(st)}", f"na{len(st)}"
    L = _header(tag, note)
    L += _v9_head()
    L += ["Vp vp 0 DC 2 AC 0.5", "Vn vn 0 DC 2 AC -0.5",
          "Xfa vp fpa vcc vee fpa OPAx388", "Xfb vn fna vcc vee fna OPAx388"]
    L += _line("a", "fpa", "pa", st)
    L += _line("b", "fna", "na", st)
    L += _common(st)
    L += [".ac dec 400 0.1 200Meg", TOPT,
          f".meas AC g_dc   FIND mag(V({pa})-V({na})) AT 0.1",
          f".meas AC g_16k  FIND mag(V({pa})-V({na})) AT 16k",
          f".meas AC g_fmod FIND mag(V({pa})-V({na})) AT 4.096Meg",
          f".meas AC g_mclk FIND mag(V({pa})-V({na})) AT 16.384Meg",
          ".end"]
    return "\n".join(L) + "\n"


