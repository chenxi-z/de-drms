# -*- coding: utf-8 -*-
"""gen_netlists_r5.py — Round 5 抗混叠阶梯 LTspice 网表生成器（V1–V9，.net 直出）

规格：docs/design/spec/2026-10-18-aa-driver-design.md sec 5.1 标准测试条件 / sec 7 复测清单
计划：docs/design/spec/2026-10-18-aa-driver-plan.md Task 4

设计要点
--------
* **全部走 `.net`**：计划 Global Constraints —— 锁屏时 `.asc` 批处理会挂死。
* 拓扑严格镜像 `opt_engine.ladder_matrices()`：
      源 — Rs(1 Ω) — x0 — R1 — x1(C1) — R2 — x2(C2) — … — R_N — xN(C_N)
  两线对称；**末级**跨接 C_diff；130 kΩ 差分负载（DM 等效 65 kΩ/线）；5 pF 引脚电容。
  这样 V1–V3 可与理论引擎逐项对拍（规格 sec 8 交叉验证）。
* 标准测试条件（sec 5.1，执行者不得改动）：
      AC 1 V（差分或共模）、DC 偏置 2.0 V、源阻抗 0 Ω（V1–V6 理想源阶段）。

仿真清单（sec 7）
--------------
  V1  标称 AC 差分               → D1 / D3 / D4 / D10
  V2  标称 AC 共模               → D2
  V3  失配角 AC 共模（B 线 ×1.01）→ D8
  V4  最坏角瞬态建立（R+1%/C+5%） → D5
  V4b 高源阻抗工况（600 kΩ + 未自举输入电容，D5 附加）
  V5  蒙特卡洛 AC ×30（逐元件独立）→ D7
  V6  蒙特卡洛瞬态 ×30            → D5 统计
  V7  噪声 .noise 0.1 Hz–fMOD/2   → D6
  V8  Kickback（ADC 采样开关）    → D9（Ron = 1 / 100 / 1000 Ω 三档灵敏度）
  V9  真实 OPA388（TI SBOMAB3 OPAx388.LIB）→ 重跑 V1/V2/V4/V7

源内阻 `RS` 的两套口径（**A 案复测实测**，见 `r5_results_A.json` 的 `xcheck` 段）
---------------------------------------------------------------------------
* 规格 sec 5.1：V1–V6 源阻抗 **0 Ω**（理想源）→ `--rs 0`，这是**正式评分口径**
* `opt_engine.ladder_matrices()` 第 20 行把源内阻硬编码 **1 Ω**（数值稳定用）
  → `--rs 1`（默认），供 sec 8 交叉验证做**同拓扑对拍**
* 两者在 A 案 @fMOD 相差 **1.08 dB**，超 sec 8 的 0.5 dB 判据 —— 故必须同口径比对，
  不得拿 `--rs 0` 的 LTspice 结果直接对 `--rs 1` 的理论预测。

用法
----
    python gen_netlists_r5.py                 # 默认只出方案 C（Task 4/5 指定）
    python gen_netlists_r5.py --cand A,B,C
    python gen_netlists_r5.py --cand A --rs 0 --outdir r5_work/rs0
"""
