def gen_v3(cand, tag, m, mode="paired", note=""):
    """失配 AC 共模。mode='paired'：R×(1+m) 配 C×(1−m)；'same'：R/C 同 ×(1+m)。"""
    st = cand["stages"]
    n = len(st)
    if mode == "paired":
        stb = _scale_line(st, 1 + m, 1 - m)
    else:
        stb = _scale_line(st, 1 + m, 1 + m)
    L = _hdr(tag, note or f"mismatch CM, line-B {mode} m={m*100:g}%")
    L += ["Vp vp 0 DC 2 AC 1", "Vn vn 0 DC 2 AC 1"]
    L += _line("a", "vp", "pa", st) + _line("b", "vn", "na", stb) + _common(st)
    L += [".ac dec 200 0.1 100k", TOPT, *_save(n), ".end"]
    return "\n".join(L) + "\n"


