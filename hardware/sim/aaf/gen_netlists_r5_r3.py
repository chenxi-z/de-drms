# ------------------------------------------------------------------ V8 kickback
def gen_v8(cand, ron=1.0, real=False, tag=None, note=None,
           vp=3.2, vn=0.8, tstop="40u", maxstep="0.5n"):
    st = cand["stages"]
    n = len(st)
    tag = tag or (f"v8r_ron{ron:g}" if real else f"v8_ron{ron:g}")
    note = note or ("kickback, real OPA388 follower" if real
                    else "kickback, ideal 0ohm source (control)")
    L = _hdr(tag, note)
    L += [f".model SWK SW(Ron={_fmt(ron)} Roff=1e12 Vt=0.5 Vh=0)"]
    if real:
        L += _opa_head()
        L += [f"Vp vp 0 DC {vp}", f"Vn vn 0 DC {vn}",
              "Xfa vp fpa vcc vee fpa OPAx388", "Xfb vn fna vcc vee fna OPAx388"]
        L += _line("a", "fpa", "pa", st) + _line("b", "fna", "na", st)
    else:
        L += [f"Vp vp 0 DC {vp}", f"Vn vn 0 DC {vn}"]
        L += _line("a", "vp", "pa", st) + _line("b", "vn", "na", st)
    L += _common(st)
    L += ["Vcm vcm 0 DC 2.0"]
    pin_a, pin_b = f"pa{n}", f"na{n}"
    L += [f"S1a {pin_a} csa swp 0 SWK", f"Csa csa vcm {_fmt(ADC_CS_PF/2*1e-12)}",
          "S2a csa vcm swn 0 SWK",
          f"S1b {pin_b} csb swn 0 SWK", f"Csb csb vcm {_fmt(ADC_CS_PF/2*1e-12)}",
          "S2b csb vcm swp 0 SWK",
          "Vswp swp 0 PULSE(0 1 0 0.5n 0.5n 121.07n 244.1406n)",
          "Vswn swn 0 PULSE(0 1 122.07n 0.5n 0.5n 121.07n 244.1406n)"]
    L += _save(n, "V(csa) V(csb) V(fpa) V(fna)")
    if real:
        L += [f".tran 0 {tstop} 0 {maxstep}",
              ".options plotwinsize=0 method=gear reltol=1e-5 abstol=1e-11 "
              "vntol=1e-8 chgtol=1e-14 trtol=7", ".end"]
    else:
        L += [f".tran 0 {tstop} 0 0.1n", TOPT, ".end"]
    return "\n".join(L) + "\n"


